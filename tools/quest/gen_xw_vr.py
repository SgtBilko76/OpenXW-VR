#!/usr/bin/env python3
"""Generate the OpenXW Quest VR host from OpenTIE-VR's.

src/xw_vr/xw_vr.c         <- ~/Projekte/OpenTIE/src/tie_vr/tie_vr.c
src/xw_vr/xw_vr.h         <- ~/Projekte/OpenTIE/src/tie_vr/tie_vr.h
src/xw_remaster/vr_stereo.{c,h} <- ~/Projekte/OpenTIE/src/tie_remaster/vr_stereo.{c,h}

The OpenXR session, layers, laser pointer, recenter and virtual gamepad are
engine-level code shared by the Totally Games ports (OpenXWA-VR -> OpenTIE-VR
-> OpenXW-VR); only the game hooks differ. Re-run after pulling VR fixes into
OpenTIE-VR. Hand edits belong in the tables below so they survive
regeneration.
"""
import pathlib
import re

TIE = pathlib.Path.home() / "Projekte/OpenTIE/src"
ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "src"

# Generic renames, applied to every generated file (order matters).
RENAMES = [
    ("tie_vr/tie_vr_cockpit_panels.h", "xw_vr/xw_vr_cockpit_panels.h"),
    ("tie_vr/tie_vr.h", "xw_vr/xw_vr.h"),
    ("tie_remaster/vr_stereo.h", "xw_remaster/vr_stereo.h"),
    ("src/tie_vr", "src/xw_vr"),
    ("TIE_REMASTER_VR_STEREO_H", "XW_REMASTER_VR_STEREO_H"),
    ("TIE_VR_COCKPIT_PANELS_H", "XW_VR_COCKPIT_PANELS_H"),
    ("TIE_VR_H", "XW_VR_H"),
    ("TieVrStereoFrame", "XwVrStereoFrame"),
    ("TieVrStereoEye", "XwVrStereoEye"),
    ("TieVrCockpit", "XwVrCockpit"),
    ("TieRemasterVr_", "XwRemasterVr_"),
    ("TieRemaster_RenderFlightVr", "XwRemaster_RenderFlightVr"),
    ("TieVr_", "XwVr_"),
    ("TIE_VR_", "XW_VR_"),
    ('"OPENTIE_VR_DISABLE"', '"OPENXW_VR_DISABLE"'),
    ('"OpenTIE VR"', '"OpenXW VR"'),
    ('#define VR_LOG "tie.vr"', '#define VR_LOG "xw.vr"'),
    ('set_info.actionSetName, "tie"', 'set_info.actionSetName, "xw"'),
    ('"TIE Fighter"', '"X-Wing"'),
    # Comments
    ("src/tie_app/vr_keyboard.c", "src/xw_app/vr_keyboard.c"),
    ("(Inserted into tie_vr.c by tools/quest/gen_tie_vr.py.)",
     "(Shared with OpenTIE-VR; see tools/quest/gen_xw_vr.py.)"),
]

# xw_vr.c only: swap the OpenTIE game queries for OpenXW's.
XW_VR_EDITS = [
    ("/* Quest VR presentation for OpenTIE (shared with the X-Wing Alliance VR port).",
     "/* Quest VR presentation for OpenXW (shared with the OpenTIE and X-Wing\n"
     " * Alliance VR ports; generated by tools/quest/gen_xw_vr.py)."),
    ('#include "tie_app/settings/settings.h"\n', '#include "xw_app/settings/settings.h"\n'),
    ('#include "tie_runtime/runtime/flight_screen.h"\n'
     '#include "tie_runtime/snapshot/snapshot.h"\n',
     '#include "xw_runtime/runtime/flight_sim.h"\n'),
    ("static int vr_in_flight(void) {\n"
     "\tconst TieSnapshot* snap = TieSnapshot_Current();\n"
     "\treturn snap && snap->scene_kind == TIE_SCENE_FLIGHT;\n"
     "}",
     "static int vr_in_flight(void) { return XwFlightSim_IsActive(); }"),
    ("/* Screens inside a mission that only understand mouse and keyboard: the\n"
     " * full-screen in-flight pages (goals, map, messages, damage, wingmen, help,\n"
     " * options, replay prompt) and the OpenTIE settings overlay (Escape). They\n"
     " * get the menu controls, not the gamepad. */\n"
     "static int vr_flight_menu_active(void) {\n"
     "\treturn TieFlightScreen_Active() != TIE_FLIGHT_SCREEN_NORMAL || TieSettings_Open();\n"
     "}",
     "/* Moments inside a mission that only understand mouse and keyboard: any\n"
     " * phase where the player is not flying (pause, end-of-mission and replay\n"
     " * prompts, film room) and the OpenXW settings overlay (Escape). They get\n"
     " * the menu controls, not the gamepad. */\n"
     "static int vr_flight_menu_active(void) {\n"
     "\treturn !XwFlightSim_IsPlayerControl() || XwSettingsMenu_Open();\n"
     "}"),
]

# X-Wing has no 3D cockpit views yet: an empty view table keeps the shared
# panel code compiled but inactive.
COCKPIT_PANELS_H = """/* VR cockpit instrument panels per craft view (none yet for OpenXW; the
 * shared VR host only places panels for views listed here). */
#ifndef XW_VR_COCKPIT_PANELS_H
#define XW_VR_COCKPIT_PANELS_H

#include <stddef.h>
#include <string.h>

typedef struct XwVrCockpitPanel {
\tconst char* name;
\tfloat src[4];         /* x0, y0, x1, y1 in classic 640x480 pixels */
\tfloat position[3];    /* metres, x right, y up, -z forward */
\tfloat orientation[4]; /* x, y, z, w */
\tfloat size[2];        /* width, height in metres */
} XwVrCockpitPanel;

typedef struct XwVrCockpitView {
\tconst char*             view;
\tconst char*             xwa_model;
\tint                     has_builtin;
\tfloat                   hud_rect[4];
\tconst XwVrCockpitPanel* panels;
\tsize_t                  panel_count;
} XwVrCockpitView;

static inline const XwVrCockpitView* XwVrCockpit_FindView(const char* view_name) {
\t(void)view_name;
\treturn NULL;
}

#endif
"""


def rename(text: str) -> str:
    for old, new in RENAMES:
        text = text.replace(old, new)
    return text


def apply(text: str, edits, name: str) -> str:
    for old, new in edits:
        if old not in text:
            raise SystemExit(f"{name}: pattern not found: {old[:70]!r}")
        text = text.replace(old, new)
    return text


def write(rel: str, text: str) -> None:
    path = OUT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"wrote src/{rel}")


def main() -> None:
    vr_c = apply((TIE / "tie_vr/tie_vr.c").read_text(), XW_VR_EDITS, "tie_vr.c")
    vr_c = rename(vr_c)
    leftovers = sorted(set(re.findall(r"\b(?:Tie|TIE_|tie_)\w*", vr_c)))
    if leftovers:
        raise SystemExit(f"xw_vr.c still references OpenTIE symbols: {leftovers}")
    write("xw_vr/xw_vr.c", vr_c)
    write("xw_vr/xw_vr.h", rename((TIE / "tie_vr/tie_vr.h").read_text()))
    write("xw_vr/xw_vr_cockpit_panels.h", COCKPIT_PANELS_H)
    write("xw_remaster/vr_stereo.h", rename((TIE / "tie_remaster/vr_stereo.h").read_text()))
    write("xw_remaster/vr_stereo.c", rename((TIE / "tie_remaster/vr_stereo.c").read_text()))


if __name__ == "__main__":
    main()
